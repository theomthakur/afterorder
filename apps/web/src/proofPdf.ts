// Builds the order proof report as a PDF in the browser and downloads it directly.
import { jsPDF } from 'jspdf';

const DROP = ['Run disclosure', 'Enforced trust boundaries', 'Agent completion record', 'Verification note'];
const PURPLE: [number, number, number] = [110, 84, 255];
const INK: [number, number, number] = [43, 31, 92];
const MUTED: [number, number, number] = [107, 101, 133];

const plain = (text: string) => text
  .replace(/→/g, '->').replace(/[‘’]/g, "'").replace(/[“”]/g, '"').replace(/[–—]/g, '-').replace(/…/g, '...').replace(/[^\x00-\xFF]/g, '')
  .replace(/\*\*([^*]+)\*\*/g, '$1').replace(/`([^`]+)`/g, '$1')
  .replace(/\[([^\]]+)\]\((https?:[^)\s]+)\)/g, '$1 ($2)');

export async function exportProofPdf(url: string) {
  const full = await (await fetch(url)).text();
  const markdown = full.split(/\n(?=## )/).filter((part) => !DROP.some((title) => part.startsWith(`## ${title}`))).join('\n');

  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const margin = 44; const width = doc.internal.pageSize.getWidth() - margin * 2; const bottom = doc.internal.pageSize.getHeight() - 48;
  let y = margin;
  const ensure = (needed: number) => { if (y + needed > bottom) { doc.addPage(); y = margin; } };
  const write = (text: string, size: number, color: [number, number, number], style: 'normal' | 'bold' = 'normal', gap = 4, indent = 0) => {
    doc.setFont('helvetica', style); doc.setFontSize(size); doc.setTextColor(...color);
    for (const line of doc.splitTextToSize(text, width - indent) as string[]) { ensure(size + 2); doc.text(line, margin + indent, y); y += size + 3; }
    y += gap;
  };

  doc.setFont('helvetica', 'bold'); doc.setFontSize(20); doc.setTextColor(...INK); doc.text('After', margin, y + 6);
  doc.setTextColor(...PURPLE); doc.text('Order', margin + doc.getTextWidth('After'), y + 6);
  doc.setFont('helvetica', 'normal'); doc.setFontSize(8); doc.setTextColor(...MUTED);
  doc.text('ORDER PROOF REPORT · MONAD TESTNET', margin + width, y + 4, { align: 'right' });
  y += 18; doc.setDrawColor(...PURPLE); doc.setLineWidth(2); doc.line(margin, y, margin + width, y); y += 20;

  let title = 'afterorder-proof';
  let hideColumn = -1;
  for (const raw of markdown.split('\n')) {
    const line = raw.trimEnd();
    if (!line.trim()) { hideColumn = -1; continue; }
    if (line.startsWith('|')) {
      let cells = line.replace(/^\||\|$/g, '').split('|').map((cell) => plain(cell.trim()));
      if (cells.every((cell) => /^:?-{2,}:?$/.test(cell))) continue;
      if (cells.includes('Metadata')) hideColumn = cells.indexOf('Metadata');
      if (hideColumn >= 0) cells = cells.filter((_, index) => index !== hideColumn);
      write(cells.filter(Boolean).join('   ·   '), 8.5, INK, 'normal', 2, 6);
      continue;
    }
    const heading = line.match(/^(#{1,4}) (.*)$/);
    if (heading) {
      const level = heading[1]!.length; const text = plain(heading[2]!);
      if (level === 1) { title = text; write(text, 16, INK, 'bold', 6); }
      else { ensure(30); y += 6; write(text, level === 2 ? 12.5 : 11, INK, 'bold', 3); if (level === 2) { doc.setDrawColor(230, 225, 251); doc.setLineWidth(.8); doc.line(margin, y - 4, margin + width, y - 4); y += 4; } }
      continue;
    }
    if (/^\s*[-*] /.test(line)) { write(`•  ${plain(line.replace(/^\s*[-*] /, ''))}`, 9.5, INK, 'normal', 2, 8); continue; }
    write(plain(line), 9.5, INK, 'normal', 4);
  }

  const pages = doc.getNumberOfPages();
  for (let page = 1; page <= pages; page += 1) {
    doc.setPage(page); doc.setFont('helvetica', 'normal'); doc.setFontSize(7.5); doc.setTextColor(...MUTED);
    doc.text(`Generated by AfterOrder · ${new Date().toLocaleString()}`, margin, doc.internal.pageSize.getHeight() - 24);
    doc.text(`${page} / ${pages}`, margin + width, doc.internal.pageSize.getHeight() - 24, { align: 'right' });
  }
  doc.save(`${title.replace(/[^a-zA-Z0-9#-]+/g, '-').replace(/#/g, '').replace(/-+/g, '-').replace(/^-|-$/g, '').toLowerCase() || 'afterorder-proof'}.pdf`);
}
